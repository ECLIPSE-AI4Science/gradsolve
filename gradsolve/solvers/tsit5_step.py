"""Single Tsit5 step + tableau — the shared method core of the Tsit5 family.

Shared by the fixed-step scan (``gradsolve/solvers/fixed_step_tsit5.py``) and the
record-and-replay adjoint (``gradsolve/warp/warp_replay.py``), which re-integrates a
recorded dt sequence with exactly the same arithmetic as the fixed-step scan.
``tsit5_step`` is the single source of the 7-stage step arithmetic, so the two cannot drift
apart (k7 computed, ``_B7*k7`` term kept even though ``_B7 == 0``; FSAL deliberately not
exploited).

The Butcher tableau is the published Tsitouras (2011) pair; the high-precision constants
are transcribed from Tsitouras (2011) and cross-checked against diffrax's ``Tsit5``
tableau in the tests:

    Ch. Tsitouras, "Runge-Kutta pairs of order 5(4) satisfying only the first
    column simplifying assumption", Comput. Math. Appl. 62(2), 770-775, 2011.

The function is array-library agnostic (pure arithmetic on the inputs): pure-JAX
traceable (jit/grad/vmap-safe) and equally valid on numpy arrays.
"""

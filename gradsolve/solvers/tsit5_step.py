def tsit5_step(f, t, y, dt, p):
    """One classical Tsit5 step: ``y(t) -> y(t + dt)`` for ``dy/dt = f(t, y, p)``.

    The exact 7-stage block of the fixed-step scan spine (no scan here): all 7
    stages computed, ``_B7*k7`` term kept (``_B7 == 0``) — bit-parity over saving
    a stage. Padding contract for the replay adjoint: ``dt == 0`` is exactly an
    identity step in both value and gradient (``y + 0*sum(b_i k_i) == y``).
    """
    k1 = f(t, y, p)
    k2 = f(t + _C[0] * dt, y + dt * (_A21 * k1), p)
    k3 = f(t + _C[1] * dt, y + dt * (_A31 * k1 + _A32 * k2), p)
    k4 = f(t + _C[2] * dt, y + dt * (_A41 * k1 + _A42 * k2 + _A43 * k3), p)
    k5 = f(t + _C[3] * dt,
           y + dt * (_A51 * k1 + _A52 * k2 + _A53 * k3 + _A54 * k4), p)
    k6 = f(t + _C[4] * dt,
           y + dt * (_A61 * k1 + _A62 * k2 + _A63 * k3 + _A64 * k4 + _A65 * k5), p)
    # stage-7 node uses the b-weights (FSAL row); k7 carries b7=0 weight below.
    k7 = f(t + _C[5] * dt,
           y + dt * (_B1 * k1 + _B2 * k2 + _B3 * k3 + _B4 * k4 + _B5 * k5 + _B6 * k6),
           p)
    return y + dt * (
        _B1 * k1 + _B2 * k2 + _B3 * k3 + _B4 * k4 + _B5 * k5 + _B6 * k6 + _B7 * k7
    )
